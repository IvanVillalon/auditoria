<h2>Políticas de devolución</h2>

<div class="politicas_devolucion">

    <p>1. Las devoluciones deben realizarse dentro de los 30 días posteriores a la fecha de compra.</p>

    <p>2. El producto debe estar en su estado original, sin signos de uso y con su embalaje intacto.</p>

    <p>3. Se requiere el comprobante de compra para procesar cualquier devolución.</p>

    <p>4. Si el producto presenta daños o defectos de fábrica, se realizará un cambio o reembolso completo según la preferencia del cliente, después de ser revisado por los técnicos.</p>

    <p>5. No se puede ajustar el precio de los productos ya vendidos.</p>

    <p>6. En caso de devoluciones parciales, el cliente puede optar por un reembolso parcial o un cambio por otro producto de igual valor.</p>

    <p>7. Variedades Full 2000 tendrá un plazo de 20 días hábiles para realizar el proceso de devolución. Si se supera este plazo, el cliente podrá realizar el reclamo correspondiente.</p>

</div>